// Generates src/lib/messages/library.generated.ts and supabase/migrations/0003_seed_messages.sql
// from docs/TONE_AND_COPY.md §5 (the source of truth for copy). Run: node scripts/gen-messages.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const md = readFileSync(new URL("../docs/TONE_AND_COPY.md", import.meta.url), "utf8");
const section = md.split(/^## 5\./m)[1] ?? "";
const out = [];
let cat = null;
for (const line of section.split("\n")) {
  const h = line.match(/^### (\w+)/);
  if (h) { cat = h[1]; continue; }
  if (/^## /.test(line)) break;
  const b = line.match(/^- (.+)$/);
  if (b && cat) out.push({ category: cat, text: b[1].trim() });
}
const rows = out.map((m) => ({ id: createHash("sha1").update(`${m.category}:${m.text}`).digest("hex").slice(0, 12), ...m }));
writeFileSync(new URL("../src/lib/messages/library.generated.ts", import.meta.url),
  `// GENERATED by scripts/gen-messages.mjs from docs/TONE_AND_COPY.md — do not edit by hand.\nimport type { Message } from "./engine";\n\nexport const MESSAGE_LIBRARY: Message[] = ${JSON.stringify(rows.map((r) => ({ ...r, active: true })), null, 2)};\n`);
const q = (s) => `'${s.replace(/'/g, "''")}'`;
writeFileSync(new URL("../supabase/migrations/0003_seed_messages.sql", import.meta.url),
  `-- GENERATED by scripts/gen-messages.mjs from docs/TONE_AND_COPY.md — do not edit by hand.\ninsert into public.messages (id, category, text, active) values\n${rows.map((r) => `  (${q(r.id)}, ${q(r.category)}, ${q(r.text)}, true)`).join(",\n")}\non conflict (id) do update set category = excluded.category, text = excluded.text, active = true;\n`);
console.log(`${rows.length} messages in ${new Set(rows.map((r) => r.category)).size} categories`);
